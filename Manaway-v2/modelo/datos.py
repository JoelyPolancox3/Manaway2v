def _pos_en_ruta(ruta_id: int, indice: int):
    """Coordenadas de una parada del recorrido (para ubicar unidades)."""
    ruta = next(r for r in rutas if r.id == ruta_id)
    parada = next(p for p in paradas
                  if p.id == ruta.paradas_ids[indice % len(ruta.paradas_ids)])
    return parada.latitud, parada.longitud


def _unidad(uid: int, ruta_id: int, placa: str, indice: int,
            sentido: int = 1, vel: float = 22.0,
            estado_unidad: str = "en ruta") -> Unidad:
    """Crea una unidad avanzando hacia la parada `indice`.

    La posición inicial se coloca en la parada ANTERIOR (según el
    sentido), para que al primer tick la simulación tenga distancia que
    recorrer y la unidad se mueva de verdad.
    """
    ruta = next(r for r in rutas if r.id == ruta_id)
    pos = (indice - sentido) % len(ruta.paradas_ids)
    latitud, longitud = _pos_en_ruta(ruta_id, pos)
    return Unidad(uid, ruta_id, placa, latitud, longitud,
                  estado=estado_unidad, velocidad_kmh=vel,
                  indice_parada=indice % len(ruta.paradas_ids),
                  sentido=sentido)

